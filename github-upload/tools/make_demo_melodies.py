#!/usr/bin/env python3
"""Generate the demo melody bank shipped in ``micropython/melodies.py``.

The tunes are synthesised from sine waves with a short attack/release
envelope, encoded as MB8 and written out as MicroPython source. Re-run this
script after changing the notes; it overwrites ``micropython/melodies.py``.

    python3 tools/make_demo_melodies.py
"""

import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

from make_melody import encode_pcm, format_python  # noqa: E402

RATE = 7812
TARGET = os.path.join(ROOT, 'micropython', 'melodies.py')

# note name -> frequency in Hz
NOTES = {
    'C4': 261.63, 'D4': 293.66, 'E4': 329.63, 'F4': 349.23, 'G4': 392.00,
    'A4': 440.00, 'B4': 493.88, 'C5': 523.25, 'D5': 587.33, 'E5': 659.25,
    'F5': 698.46, 'G5': 783.99, 'A5': 880.00, 'B5': 987.77, 'C6': 1046.50,
    'E6': 1318.51, 'G6': 1567.98,
}

MELODIES = {
    # name: list of (note or None, seconds)
    'startup': [
        ('C5', 0.10), ('E5', 0.10), ('G5', 0.10), ('C6', 0.16),
        (None, 0.05), ('G5', 0.08), ('C6', 0.24),
    ],
    'coin': [
        ('B5', 0.07), ('E6', 0.28),
    ],
    'alarm': [
        ('A5', 0.12), (None, 0.05), ('A5', 0.12), (None, 0.05),
        ('A5', 0.12), (None, 0.05), ('A5', 0.18),
    ],
    'robot': [
        ('C4', 0.06), ('G4', 0.06), ('C5', 0.06), ('G5', 0.06),
        ('C6', 0.06), ('G5', 0.06), ('C5', 0.10),
    ],
}


def render(notes, rate=RATE, amplitude=110):
    """Render ``[(note, seconds), ...]`` into signed 16-bit style samples."""
    samples = []
    phase = 0.0
    for note, duration in notes:
        count = int(duration * rate)
        if note is None:
            samples.extend([0] * count)
            continue
        frequency = NOTES[note]
        step = 2.0 * math.pi * frequency / rate
        attack = max(1, int(0.004 * rate))
        release = max(1, int(0.010 * rate))
        for i in range(count):
            envelope = 1.0
            if i < attack:
                envelope = i / attack
            remaining = count - i
            if remaining < release:
                envelope = min(envelope, remaining / release)
            # A touch of second harmonic keeps it from sounding too hollow.
            value = math.sin(phase) + 0.25 * math.sin(2.0 * phase)
            samples.append(value * amplitude * envelope)
            phase += step
        phase = 0.0
    return [int(sample) for sample in samples]


def main():
    blocks = []
    for name in MELODIES:
        samples = render(MELODIES[name])
        data = encode_pcm(samples, RATE, RATE, peak=118)
        blocks.append(format_python(name, data))
        print('%-8s %6d samples  %5d bytes MB8'
              % (name, len(samples), len(data)))
    header = '''"""Melody bank for the Ultra Expansion Pack.

Generated by ``tools/make_demo_melodies.py`` - edit that script instead of
this file. Each melody is MB8 nibble-delta audio (see ``ultra_expansion``)
and is played with ``ultra.play_melody('startup')``.

Import this module after ``ultra_expansion``::

    import ultra_expansion as ultra
    import melodies
    ultra.play_melody('startup')
"""

from ultra_expansion import register_melody

'''
    body = '\n\n'.join(blocks)
    with open(TARGET, 'w', encoding='utf-8') as handle:
        handle.write(header + body + '\n')
    total = os.path.getsize(TARGET)
    print('wrote %s (%d bytes of source)' % (TARGET, total))


if __name__ == '__main__':
    main()
